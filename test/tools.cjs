const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1200, height: 860 } });
  const errs = []; p.on('pageerror', e => errs.push(String(e))); p.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
  await p.goto('file://' + process.cwd() + '/dist/index.html'); await p.waitForTimeout(400);
  let ok = true; const check = (c, m) => { console.log((c ? 'ok   ' : 'FAIL ') + m); if (!c) ok = false; };
  check(await p.evaluate(() => document.getElementById('btnCraft').disabled), 'nút Chế tác khoá khi chưa có Xưởng');
  await p.evaluate(() => { const g = window.__game, s = g.sim; s.speed = 4; s.fog.state.fill(2); s.fog.version++; s.stock.wood = 60; s.stock.stone = 30; s.villagers.forEach(v => v.fullness = 1e9); });
  await p.click('#btnShop');
  await p.evaluate(() => { const g = window.__game, s = g.sim; g.ctl.centerOn((s.world.start.x + 5) * 32, (s.world.start.y + 2) * 32); });
  const box = await p.evaluate(() => { const b = document.getElementById('view').getBoundingClientRect(); return { x: b.left + b.width / 2, y: b.top + b.height / 2 }; });
  await p.click('#btnAll');
  await p.mouse.move(box.x, box.y); await p.mouse.move(box.x + 4, box.y + 4);
  await p.screenshot({ path: '/tmp/t_ghost.png' });
  await p.mouse.click(box.x + 4, box.y + 4);
  check(await p.evaluate(() => window.__game.sim.buildings.some(b => b.kind === 'workshop')), 'đã đặt Xưởng');
  await p.waitForTimeout(2500); await p.screenshot({ path: '/tmp/t_site.png' });
  await p.waitForTimeout(6000);
  check(await p.evaluate(() => window.__game.sim.hasWorkshop()), 'Xưởng dựng xong');
  await p.keyboard.press('c');
  await p.waitForTimeout(300);
  const rows = await p.$$('#recipes .rec');
  check(rows.length === 8, 'bảng chế tác có 8 công thức');
  for (const i of [0, 2, 4, 6]) await (await rows[i].$$('button'))[1].click();
  await p.evaluate(() => { const s = window.__game.sim, v = s.villagers; s.setJob([v[0].id], 'craft'); s.setJob([v[1].id], 'wood'); s.setJob([v[2].id], 'stone'); });
  await p.waitForTimeout(5000); await p.screenshot({ path: '/tmp/t_craft.png' });
  await p.waitForTimeout(8000);
  console.log(JSON.stringify(await p.evaluate(() => ({ ts: window.__game.sim.toolStock, q: window.__game.sim.craftQueue, tools: window.__game.sim.villagers.map(v => [v.name, v.job, v.phase, v.tools.axe && v.tools.axe.tier, v.tools.pick && v.tools.pick.tier]) }))));
  await p.keyboard.press('c');
  await p.evaluate(() => { window.__game.cam.zoom = 4; });
  let seen = '';
  for (let k = 0; k < 40; k++) {
    const st = await p.evaluate(() => { const g = window.__game, v = g.sim.villagers[1]; g.ctl.centerOn(v.x * 32, v.y * 32 - 10); return v.phase + ':' + v.anim + ':' + (v.tools.axe ? v.tools.axe.tier : 0) + ':' + (v.slide ? 'slide' : 'noslide'); });
    seen = st;
    if (st.startsWith('work:chop') && st.endsWith('noslide')) break;
    await p.waitForTimeout(500);
  }
  console.log('villager 1:', seen);
  check(seen.startsWith('work:chop:1'), 'Tia đã nhận rìu gỗ và đang chặt bằng rìu');
  await p.evaluate(() => { window.__game.sim.speed = 1; });
  await p.waitForTimeout(150);
  await p.screenshot({ path: '/tmp/t_close.png' });
  console.log('errors', errs); console.log(ok ? 'PASS' : 'FAIL'); await b.close();
})();
