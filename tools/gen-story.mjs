// The story tree as data: writes src/data/story/ from the tables of tools/story/stone.mjs and tools/story/medieval.mjs (taken from doc/story_tree.md). Safe to run again.
//   node tools/gen-story.mjs            then   node tools/simStory.mjs --check
// Edit the tables, never the JSON. The generator adds the id prefixes (thread:, chapter:, knot:, leaf:, fruit:, tip:), turns the marks of each answer ('uy+2 tin-1') into a deed of its own
// (marks.json `deeds`), and checks what it can see (unknown leaves, villages, characters). The rules are checked by simStory --check (storydata.validateStory).
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as stone from './story/stone.mjs';
import * as medieval from './story/medieval.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..'), dir = join(root, 'src/data/story');
const J = (p) => JSON.parse(readFileSync(p, 'utf8'));
const W = (p, o) => { mkdirSync(dirname(p), { recursive: true }); const crlf = existsSync(p) && readFileSync(p, 'utf8').includes('\r\n'); writeFileSync(p, JSON.stringify(o, null, 1).replace(/\n/g, crlf ? '\r\n' : '\n') + (crlf ? '\r\n' : '\n')); };
const errors = [];
const NOTE = 'Written by tools/gen-story.mjs from tools/story/*.mjs (doc/story_tree.md). Edit the tables there and run the script again; do not edit this file.';

// ---- the villages of the land (Rễ): the ids a world effect may name
const ROOTS = [
  { id: 'spring', name: 'Suối Nguồn', role: 'thương lái, người lang thang, đoàn người đi đường', shadow: 'mạng buôn đá obsidian thời Tân thạch' },
  { id: 'swamp', name: 'Đầm Lầy', role: 'người tị nạn, thương lái lừa đảo', shadow: 'dân nhà sàn ven hồ vùng Alps' },
  { id: 'axe', name: 'Rìu Đá', role: 'do thám, đòi cống, tối hậu thư', shadow: 'Danegeld: trả càng nhiều bị đòi càng lớn' },
  { id: 'cave', name: 'Hang Gấu', role: 'đòi cống, kẻ đuổi theo, lửa thiêng', shadow: 'Göbekli Tepe, lửa thiêng đền Vesta' },
  { id: 'dune', name: 'Đồi Cát', role: 'làng xa', shadow: '' }, { id: 'harbor', name: 'Bến Cá', role: 'làng xa', shadow: '' }, { id: 'ridge', name: 'Đỉnh Gió', role: 'làng xa', shadow: '' },
];
const TRIBES = new Set([...ROOTS.map((r) => r.id), '@boss']);
const CHARS = new Set(readdirSync(join(root, 'src/data/characters')).map((f) => f.replace('.json', '')));

// ---- the deeds the old visitor scripts leave (doc "Deed cũ đẩy Dấu nào") and the two of the game
const DEEDS = {
  helped_wanderer: 'nhan+1', took_in_wanderer: 'nhan+2 hop+1', refused_wanderer: 'nhan-1', took_in_thief: 'hop+1', thief_again: 'lo+2', pardoned_thief: 'nhan+1 lo+1', punished_thief: 'nhan-1 uy+1',
  hosted_travelers: 'nhan+1 tin+1 lo+1', took_refugees: 'nhan+2 lo+1 hop+2', fed_refugees: 'nhan+1', refused_refugees: 'nhan-2', handed_over: 'nhan-3 tin+1', paid_pursuers: 'uy-1 lo+1', defied_pursuers: 'nhan+1 uy+2 tin-1',
  hosted_scouts: 'tin+2 lo+1', showed_force: 'uy+3', showed_weakness: 'uy-1 lo+3', drove_off_scouts: 'uy+1 tin-2', paid_tribute: 'uy-1 tin+1 lo+1', refused_tribute: 'uy+1 tin-1', scared_off_tribute: 'uy+3', drove_off_tribute: 'uy+1 tin-1',
  bluff_failed: 'uy-3 lo+2', bought_peace: 'tin+1 lo+1', bought_time: 'lo+1', defied_ultimatum: 'uy+2', paid_ransom: 'nhan+2 tin+1', refused_ransom: 'nhan-2',
};
const marksOf = (spec) => Object.fromEntries(String(spec).trim().split(/\s+/).filter(Boolean).map((t) => { const m = /^([a-z]+)([+-]\d+(?:\.\d+)?)$/.exec(t); if (!m) { errors.push(`bad marks "${spec}"`); return ['?', 0]; } return [m[1], Number(m[2])]; }));
const deedTable = {};
const addDeed = (key, spec) => { const row = marksOf(spec); if (deedTable[key] && JSON.stringify(deedTable[key]) !== JSON.stringify(row)) errors.push(`deed ${key}: two meanings`); deedTable[key] = row; };
for (const [k, v] of Object.entries({ ...DEEDS, ...stone.deeds, ...medieval.deeds })) addDeed(k, v);

// ---- a scene: each answer gets a deed of its own for its marks; `deed` of the table is a tag left beside it; give / take / rel / raid / sflag are effects of the talk
function scene(owner, s) {
  if (s.cast && !CHARS.has(s.cast)) errors.push(`${owner}: no character ${s.cast}`);
  const key = owner.replace(/^(\w)\w*:/, '$1_').replace(/[^\w]/g, '');
  return { say: s.say, ...(s.cast ? { cast: s.cast } : {}), options: s.options.map((x, i) => {
    const effects = [];
    if (x.deed) { effects.push({ deed: x.deed }); deedTable[x.deed] ??= {}; }
    for (const k of ['give', 'take', 'rel', 'raid', 'sflag']) if (x[k] !== undefined) effects.push({ [k]: x[k] });
    const out = { text: x.text, reply: x.reply };
    if (x.marks) { out.deed = `${key}_${i + 1}`; addDeed(out.deed, x.marks); }
    if (effects.length) out.effects = effects;
    if (x.cond) out.cond = x.cond;
    return out;
  }) };
}
const worldCheck = (where, list) => { for (const e of list ?? []) { for (const t of [e.rel?.tribe, e.raid?.tribe]) if (t && !TRIBES.has(t)) errors.push(`${where}: unknown village ${t}`); if (e.deed && !deedTable[e.deed]) errors.push(`${where}: the deed ${e.deed} has no marks (add it to \`deeds\`)`); } };
const affinity = (spec) => Object.fromEntries(String(spec).trim().split(/\s+/).filter(Boolean).map((t) => { const [m, v] = t.split(':'); return [m, Number(v)]; }));
const L = (id) => `leaf:${id}`;

function tree(id, T) {
  const leafIds = new Set([...T.leaves, ...T.wild].map((l) => l.id));
  const threads = T.threads.map((t) => ({ id: `thread:${t.id}`, name: t.name, trunk: t.trunk, tree: id, chapters: t.chapters.map((c, i) => {
    const cid = `chapter:${t.id}-${i + 1}`;
    return { id: cid, name: c.name, ...(c.script ? { script: c.script, options: c.options } : { scene: scene(cid, c.scene) }), ...(c.when ? { when: c.when } : {}), ...(c.days ? { days: c.days } : {}) };
  }) }));
  const knots = T.knots.map((k) => {
    for (const [leaf] of k.leaves) if (!leafIds.has(leaf)) errors.push(`knot ${k.id}: no leaf ${leaf}`);
    if (!leafIds.has(k.fallback)) errors.push(`knot ${k.id}: no fallback leaf ${k.fallback}`);
    return { id: `knot:${k.id}`, name: k.name, tree: id, trunk: k.trunk, fedBy: k.fedBy.map((x) => `thread:${x}`), when: { chapters: k.chapters, ...(k.progress ? { progress: k.progress } : {}), ...(k.fire ? { fire: k.fire } : {}), ...(k.cond ? { cond: k.cond } : {}) }, fallback: L(k.fallback),
      leaves: k.leaves.map(([leaf, base, aff, tilt]) => ({ leaf: L(leaf), base, ...(aff ? { affinity: affinity(aff) } : {}), ...(tilt?.length ? { tilt: tilt.map(([c, mul]) => ({ if: c, mul })) } : {}) })) };
  });
  const leaf = (l) => { worldCheck(l.id, l.effects); return { ...l, id: L(l.id), ...(l.alt ? { alt: L(l.alt) } : {}), ...(l.scene ? { scene: scene(L(l.id), l.scene) } : {}) }; };
  const fruits = T.fruits.map((f) => {
    for (const l of f.needs.flat()) if (!leafIds.has(l)) errors.push(`fruit ${f.id}: no leaf ${l}`);
    return { ...f, id: `fruit:${f.id}`, tree: id, needs: f.needs.map((n) => (Array.isArray(n) ? n.map(L) : L(n))), ...(f.scene ? { scene: scene(`fruit:${f.id}`, f.scene) } : {}) };
  });
  const tips = T.tips.map((t) => ({ ...t, id: `tip:${t.id}`, tree: id, fruits: t.fruits.map((f) => `fruit:${f}`), leaves: t.leaves.map(L), ...(t.flowTo ? { flowTo: `tip:${t.flowTo}` } : {}) }));
  W(join(dir, id, 'threads.json'), { _note: NOTE, threads });
  W(join(dir, id, 'knots.json'), { _note: NOTE, knots });
  W(join(dir, id, 'leaves.json'), { _note: NOTE, leaves: T.leaves.map(leaf) });
  W(join(dir, id, 'wild.json'), { _note: NOTE, leaves: T.wild.map(leaf) });
  W(join(dir, id, 'fruits.json'), { _note: NOTE, fruits });
  W(join(dir, id, 'tips.json'), { _note: NOTE, tips });
  return { threads, knots, leaves: T.leaves.length, wild: T.wild.length, fruits, tips };
}
const S = tree('stone', stone), M = tree('medieval', medieval);

W(join(dir, 'stone/legacy.json'), { _note: `${NOTE} What each stone-age tip leaves to the medieval age: marks to begin with, the trunk that comes first, leaf weights (tilt), game multipliers (mods: marketFee, marketQuota, craftSpeed, researchSpeed).`,
  legacy: Object.fromEntries(Object.entries(stone.legacy).map(([t, l]) => [`tip:${t}`, { ...l, ...(l.tilt ? { tilt: Object.fromEntries(Object.entries(l.tilt).map(([k, v]) => [L(k), v])) } : {}) }])) });

// marks.json: the marks stay as they are; the deeds and the rumours are written anew
const marksPath = join(dir, 'marks.json'), marks = J(marksPath);
W(marksPath, { _note: marks._note, marks: marks.marks, deeds: deedTable, rumors: stone.rumors });

// index.json: the tree is awake in the game from Phase 5
const indexPath = join(dir, 'index.json'), index = J(indexPath);
W(indexPath, { ...index, enabled: true, trees: index.trees.map((t) => (t.id === 'medieval' ? { ...t, tipMin: 3 } : t)) }); // a medieval tip needs a fruit (3 points) or three fallen leaves: with less the default one stands (doc: M7 'không đủ Trái')

W(join(dir, 'world/roots.json'), { _note: `${NOTE} The villages of the land a leaf may name (rel, raid), with the part each plays in the tree and its shadow in history.`, villages: ROOTS });
for (const q of medieval.questFlags) if (!J(join(dir, 'quests/side_quests.json')).quests.some((x) => x.id === q.quest)) errors.push(`from_flags: no side quest ${q.quest}`);
W(join(dir, 'quests/from_flags.json'), { _note: `${NOTE} A flag of the tree makes a side quest likelier to be offered (config.weight times); nothing else joins the quests to the tree.`, weight: 3, flags: medieval.questFlags });

// unlocks.json: the specialists stay (tools/gen-specialists.mjs writes them); the powers of the tips are added, and the table is demanded whole from now on (strict)
const unPath = join(dir, 'unlocks.json'), un = J(unPath);
const kept = un.unlocks.filter((u) => u.kind !== 'perk');
const perks = medieval.powers.map((p) => ({ key: `perk:${p.id}`, kind: 'perk', from: [`tip:${p.tip}`], sources: ['story'], core: false, name: p.name, about: p.about }));
W(unPath, { ...un, strict: true, unlocks: [...kept, ...perks] });

if (errors.length) { for (const e of errors) console.error(`ERROR  ${e}`); process.exit(1); }
const count = (x) => `${x.threads.length} branches (${x.threads.reduce((a, t) => a + t.chapters.length, 0)} stages), ${x.knots.length} knots, ${x.leaves} leaves + ${x.wild} wild, ${x.fruits.length} fruits, ${x.tips.length} tips`;
console.log(`stone:    ${count(S)}\nmedieval: ${count(M)}\ndeeds: ${Object.keys(deedTable).length}, powers: ${perks.length}, quest flags: ${medieval.questFlags.length}`);
